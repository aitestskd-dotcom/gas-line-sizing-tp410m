const C=require('../src/core.js'), assert=require('assert');
const near=(a,b,t,m)=>assert(Math.abs(a-b)<=t,`${m}: ${a} vs ${b}`);
const base={mdot:5242/3600,P1:(22+C.ATM)*1e5,rho1:19.02,mu:0.0118e-3,L:100,D:0.1023,eps:28e-6,kMinor:0};
const r=C.gasSolve(base);
near(r.P2/1e5-C.ATM,21.8765,2e-3,'P2 barg (independent solver)');
near(r.dP,0.1235,1e-3,'dP');
assert(r.residual<1e-9,'residual');
assert(C.gasSolve({...base,mdot:r.mmax*1.2}).choked,'choke detection');
const c={vmax:10,dpmax:0.1}, mf=C.gasMaxFlow(base,c);
const at=C.gasSolve({...base,mdot:mf.mdot}); near(at.dP100,0.1,1e-6,'max flow sits on dP limit');
assert(!C.gasScan(base,c,base.mdot).find(x=>x.nps==='4').p.all,'NPS4 fails dP at base case');
assert(C.gasScan(base,c,base.mdot).find(x=>x.nps==='6').p.all,'NPS6 passes');
const pts=[[0,60,0,2],[100,58,55,2.5],[200,53,72,3.2],[300,45,78,4.5],[400,34,72,6.5],[500,20,55,9.5]].map(a=>({Q:a[0],H:a[1],eta:a[2],npshr:a[3]}));
const s={fluid:{rho:998,mu:1e-3,pvap:0.032},suc:{D:0.2545,L:15,eps:45e-6,K:3},dis:{D:0.2027,L:800,eps:45e-6,K:20},zs:3,zd:20,Ps:0,Pd:2};
const crit={npshRatio:1.25,porLow:70,porHigh:120,vLiq:3,vSuc:1.5};
const a=C.pumpAnalyse(s,pts,1,250,crit);
near(a.Q,213.39,0.05,'operating flow'); near(Math.abs(C.pumpHead(a.coef,a.Q,1)-C.sysHead(s,a.Q).H),0,1e-6,'curves intersect');
const b=C.pumpAnalyse(s,pts,1.1,250,crit); assert(b.Q>a.Q,'speed raises flow');
near(C.opPoint(s,pts,a.coef,1)*1.1/1.1,a.Q,1e-9,'repeatable');
assert(a.speedNeeded>1&&a.speedNeeded<1.2,'speed needed');
assert(C.pumpAnalyse({...s,zd:200},pts,1,250,crit).noFlow,'no-flow when static > shutoff');
console.log('All tests passed');
